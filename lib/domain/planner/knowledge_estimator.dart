// Оценка знаний пользователя по диагностическому тесту (слой domain, planner).
// По ответам теста определяет, какие темы пользователь уже знает и может не
// изучать. Вызывается из OnboardingController (мастер создания плана), а
// найденные темы затем исключает из плана PlanGenerator.

import '../entities/topic.dart';

/// Определяет, какие темы пользователь уже знает, по ответам диагностического теста.
///
/// Правила:
/// * верный ответ по теме означает, что известны сама тема и все её
///   предшественники в графе (кто знает Riverpod, знает и основы Dart);
/// * неверный ответ (или «Не знаю») означает, что тема не известна, даже если
///   её «покрыл» верный ответ по более сложной теме — явный провал важнее.
class KnowledgeEstimator {
  /// Константный конструктор: у класса нет полей (состояния), поэтому его
  /// можно создавать как `const KnowledgeEstimator()`.
  const KnowledgeEstimator();

  /// [answers] — для каждой темы с вопросом: `true`, если ответ верный.
  ///
  /// [topics] — все темы направления (вершины графа). Возвращает множество
  /// id тем, которые пользователь уже знает.
  Set<String> knownTopics(List<Topic> topics, Map<String, bool> answers) {
    // Словарь «id темы → тема», чтобы быстро находить тему по её id.
    final byId = {for (final t in topics) t.id: t};
    // Множество id тем, которые считаем известными (сначала пустое).
    final known = <String>{};

    // Вложенная функция: отмечает тему и всех её предшественников
    // (зависимости, зависимости зависимостей и т. д.) как известные.
    // Это обход графа в глубину с помощью стека, без рекурсии.
    void markWithAncestors(String id) {
      // Стек тем, которые ещё нужно обработать; начинаем с самой темы.
      final stack = [id];
      // Пока в стеке есть темы — обрабатываем их по одной.
      while (stack.isNotEmpty) {
        // Достаём из стека последнюю добавленную тему.
        final current = stack.removeLast();
        // add() вернёт false, если тема уже была отмечена: её
        // предшественники тоже уже обработаны, поэтому пропускаем.
        if (!known.add(current)) continue;
        // Ищем тему в словаре (её может не быть, если id неизвестен).
        final topic = byId[current];
        // Кладём в стек все темы, от которых зависит текущая.
        if (topic != null) stack.addAll(topic.prerequisites);
      }
    }

    // Для каждого верного ответа по существующей теме отмечаем эту тему
    // вместе со всеми её предшественниками.
    answers.forEach((topicId, correct) {
      if (correct && byId.containsKey(topicId)) markWithAncestors(topicId);
    });

    // Темы с неверным ответом (или «Не знаю»). Явный провал важнее, поэтому
    // убираем их из известных, даже если их «покрыла» более сложная тема.
    final failed = answers.entries.where((e) => !e.value).map((e) => e.key);
    known.removeAll(failed);
    // Оставляем только id, которые реально есть в направлении: зависимость
    // могла ссылаться на тему, которой нет в списке.
    known.retainAll(byId.keys);
    // Итог — множество id тем, которые можно не изучать.
    return known;
  }
}
